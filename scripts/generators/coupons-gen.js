function generateCoupons(registerQA) {
  console.log('[8/10] 正在生成 12 篇【优惠码】专栏文章 (深度定制，彻底消灭模版重复)...');
  const coupDir = path.join(contentDir, 'coupons');
  ensureDir(coupDir);

  coupItems.forEach((item, idx) => {
    const meta = {
      title: item.title,
      description: `针对【${item.primary}】展开深度核验：汇总真实可用的专属优惠码、折让比例、适用套餐范围与结算实测。`,
      section: "coupons",
      primaryKeyword: item.primary,
      secondaryKeywords: item.supporting,
      date: `2026-09-${String(10 + (idx % 12)).padStart(2, '0')}T10:00:00+08:00`,
      lastmod: "2026-09-28T12:00:00+08:00"
    };

    const lead = `精打细算享受高品质网络服务是每一位理性消费者的追求。合理把握服务商官方的促销活动与专属优惠码，往往能以平价开销拿下高规格的专线加速方案。本文围绕【${item.primary}】，为您梳理清晰的折扣机制与结算省钱实战技巧。`;

    const sections = getCouponSections(item);

    const q1Obj = registerQA(item.q1, item.a1, `coupons/${item.slug}`);
    const q2Obj = registerQA(item.q2, item.a2, `coupons/${item.slug}`);
    const faq = [q1Obj, q2Obj];

    const conclusion = `理性把握【${item.primary}】的优惠窗口，花更少的预算享受更稳固的专线加速服务。前往服务商官方结算页核对即时活动有效期，安全下单省心用网。`;

    writeArticle(coupDir, item.slug, meta, lead, sections, faq, conclusion);
  });

  console.log('✅ 12 篇【优惠码】文章生成完毕（彻底消除重复段落）！');
}

module.exports = { generateCoupons };
